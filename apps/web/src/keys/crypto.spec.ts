import { server } from 'vitest/browser';
import { fromBase64Url, toBase64Url, utf8 } from './bytes.js';
import {
  INFO,
  OpenError,
  aesGcmOpen,
  aesGcmSeal,
  constantTimeEqual,
  exportAesKey,
  exportPublicKey,
  generateAesKey,
  generateKeyPair,
  hmacSha256,
  hpkeOpen,
  hpkeSeal,
  importAesKey,
  type WrapInfo,
} from './crypto.js';
import { deterministicBytes, withDeterministicRandom, withFixedRandom, x25519FromPrivateKey } from './testing.js';

// The vectors shared with the Runner (apps/runner/internal/keys/vectors_test.go),
// read from the project's root (apps/web).
const fixtures = '../../packages/contracts/fixtures/crypto/';
const readVectors = async <T>(name: string): Promise<T> =>
  JSON.parse(await server.commands.readFile(fixtures + name)) as T;

const fromHex = (hex: string): Uint8Array<ArrayBuffer> =>
  new Uint8Array(hex.match(/../g)?.map((byte) => parseInt(byte, 16)) ?? []);

const flipBit = (bytes: Uint8Array, at: number): Uint8Array<ArrayBuffer> => {
  const copy = new Uint8Array(bytes);
  copy[at] = (copy[at] ?? 0) ^ 0x01;
  return copy;
};

interface RfcVector {
  mode: number;
  kem_id: number;
  kdf_id: number;
  aead_id: number;
  info: string;
  skRm: string;
  pkRm: string;
  skEm: string;
  enc: string;
  aad: string;
  pt: string;
  ct: string;
}

interface WrapCase {
  name: string;
  seed: string;
  recipientPrivateKey: string;
  recipientPublicKey: string;
  info: WrapInfo;
  aad: string;
  plaintext: string;
  enc: string;
  ciphertext: string;
}

interface AesGcmCase {
  name: string;
  seed: string;
  key: string;
  aad: string;
  plaintext: string;
  sealed: string;
}

interface HmacVectors {
  hmac: { name: string; secret: string; message: string; mac: string }[];
  constantTimeEqual: { a: string; b: string; equal: boolean }[];
}

const b = fromBase64Url;

describe('the RFC 9180 vector', () => {
  const rfc = () => readVectors<RfcVector>('hpke-rfc9180.json');

  it('is the suite Crewdeck uses', async () => {
    const v = await rfc();
    expect([v.mode, v.kem_id, v.kdf_id, v.aead_id]).toEqual([0, 0x20, 0x01, 0x02]);
  });

  it('opens', async () => {
    const v = await rfc();
    const { privateKey } = await x25519FromPrivateKey(fromHex(v.skRm));
    const pt = await hpkeOpen(privateKey, fromHex(v.enc), fromHex(v.ct), fromHex(v.info), fromHex(v.aad));
    expect(pt).toEqual(fromHex(v.pt));
  });

  it('reseals identically with its ephemeral key', async () => {
    const v = await rfc();
    const sealed = await withFixedRandom(fromHex(v.skEm), () =>
      hpkeSeal(fromHex(v.pkRm), fromHex(v.pt), fromHex(v.info), fromHex(v.aad)),
    );
    expect(sealed.enc).toEqual(fromHex(v.enc));
    expect(sealed.ciphertext).toEqual(fromHex(v.ct));
  });
});

describe('the wraps generated by the Runner', () => {
  const cases = async () => (await readVectors<{ cases: WrapCase[] }>('crewdeck-wrap.json')).cases;

  it('open, and fail with a flipped bit or another additional data', async () => {
    for (const c of await cases()) {
      const { privateKey, publicKey } = await x25519FromPrivateKey(b(c.recipientPrivateKey));
      expect(publicKey, c.name).toEqual(b(c.recipientPublicKey));
      expect(await hpkeOpen(privateKey, b(c.enc), b(c.ciphertext), c.info, b(c.aad)), c.name).toEqual(b(c.plaintext));

      const ct = b(c.ciphertext);
      await expect(hpkeOpen(privateKey, b(c.enc), flipBit(ct, ct.length >> 1), c.info, b(c.aad))).rejects.toThrow(OpenError);
      await expect(hpkeOpen(privateKey, flipBit(b(c.enc), 31), ct, c.info, b(c.aad))).rejects.toThrow(OpenError);
      await expect(hpkeOpen(privateKey, b(c.enc), ct, c.info, utf8(`${c.name}:other`))).rejects.toThrow(OpenError);
    }
  });

  it('reseal byte for byte from the same seed', async () => {
    for (const c of await cases()) {
      const sealed = await withDeterministicRandom(b(c.seed), () =>
        hpkeSeal(b(c.recipientPublicKey), b(c.plaintext), c.info, b(c.aad)),
      );
      expect(toBase64Url(sealed.enc), c.name).toBe(c.enc);
      expect(toBase64Url(sealed.ciphertext), c.name).toBe(c.ciphertext);
    }
  });
});

describe('the AES-256-GCM seals generated by the Runner', () => {
  const cases = async () => (await readVectors<{ cases: AesGcmCase[] }>('aes-gcm.json')).cases;

  it('open, and fail with a flipped bit or another additional data', async () => {
    for (const c of await cases()) {
      const key = await importAesKey(b(c.key));
      expect(await aesGcmOpen(key, b(c.sealed), b(c.aad)), c.name).toEqual(b(c.plaintext));
      const sealed = b(c.sealed);
      for (const at of [0, 12, sealed.length - 1]) {
        await expect(aesGcmOpen(key, flipBit(sealed, at), b(c.aad))).rejects.toThrow(OpenError);
      }
      await expect(aesGcmOpen(key, sealed, utf8(`${c.name}:other`))).rejects.toThrow(OpenError);
    }
  });

  it('reseal byte for byte from the same seed, the key drawn first', async () => {
    for (const c of await cases()) {
      const { key, sealed } = await withDeterministicRandom(b(c.seed), async () => {
        const key = await generateAesKey({ extractable: true });
        return { key, sealed: await aesGcmSeal(key, b(c.plaintext), b(c.aad)) };
      });
      expect(toBase64Url(await exportAesKey(key)), c.name).toBe(c.key);
      expect(toBase64Url(sealed), c.name).toBe(c.sealed);
    }
  });
});

describe('HMAC-SHA256 and the constant-time comparison', () => {
  it('match the vectors', async () => {
    const v = await readVectors<HmacVectors>('hmac.json');
    for (const c of v.hmac) {
      expect(toBase64Url(await hmacSha256(b(c.secret), b(c.message))), c.name).toBe(c.mac);
    }
    for (const c of v.constantTimeEqual) {
      expect(constantTimeEqual(b(c.a), b(c.b)), `${c.a} = ${c.b}`).toBe(c.equal);
    }
  });
});

describe('a key holder', () => {
  it('has a non-extractable X25519 private key and a 32-byte public key', async () => {
    const pair = await generateKeyPair();
    expect(pair.privateKey.extractable).toBe(false);
    expect(pair.privateKey.algorithm.name).toBe('X25519');
    expect(await exportPublicKey(pair.publicKey)).toHaveLength(32);
    await expect(crypto.subtle.exportKey('pkcs8', pair.privateKey)).rejects.toThrow();
  });

  it('opens what is sealed for it, under a new ephemeral key each time', async () => {
    const pair = await generateKeyPair();
    const publicKey = await exportPublicKey(pair.publicKey);
    const aad = utf8('dev_01J9ZQ3M:1');
    const first = await hpkeSeal(publicKey, utf8('la clé du coffre'), INFO.vaultWrap, aad);
    const second = await hpkeSeal(publicKey, utf8('la clé du coffre'), INFO.vaultWrap, aad);
    expect(first.enc).toHaveLength(32);
    expect(first.enc).not.toEqual(second.enc);
    expect(new TextDecoder().decode(await hpkeOpen(pair.privateKey, first.enc, first.ciphertext, INFO.vaultWrap, aad))).toBe(
      'la clé du coffre',
    );
  });

  it('cannot open with another info, another key, a flipped tag, or no additional data', async () => {
    const pair = await generateKeyPair();
    const other = await generateKeyPair();
    const aad = utf8('dev_01J9ZQ3M:1');
    const { enc, ciphertext } = await hpkeSeal(await exportPublicKey(pair.publicKey), utf8('x'), INFO.vaultWrap, aad);
    await expect(hpkeOpen(pair.privateKey, enc, ciphertext, INFO.sessionKey, aad)).rejects.toThrow(OpenError);
    await expect(hpkeOpen(other.privateKey, enc, ciphertext, INFO.vaultWrap, aad)).rejects.toThrow(OpenError);
    await expect(hpkeOpen(pair.privateKey, enc, flipBit(ciphertext, ciphertext.length - 1), INFO.vaultWrap, aad)).rejects.toThrow(
      OpenError,
    );
    await expect(hpkeSeal(await exportPublicKey(pair.publicKey), utf8('x'), INFO.vaultWrap, new Uint8Array())).rejects.toThrow(
      /additional data/,
    );
    await expect(hpkeOpen(pair.privateKey, enc, ciphertext, INFO.vaultWrap, new Uint8Array())).rejects.toThrow(/additional data/);
  });

  it('refuses to seal for a low-order public key', async () => {
    await expect(hpkeSeal(new Uint8Array(32), utf8('x'), INFO.vaultWrap, utf8('aad'))).rejects.toThrow();
  });
});

describe('an AES-256 key', () => {
  it('is non-extractable unless it must be wrapped', async () => {
    expect((await generateAesKey()).extractable).toBe(false);
    const wrappable = await generateAesKey({ extractable: true });
    expect(await exportAesKey(wrappable)).toHaveLength(32);
  });

  it('seals as nonce ‖ ciphertext ‖ tag under a new nonce each time', async () => {
    const key = await generateAesKey();
    const aad = utf8('ses_01J9ZQ5X:7');
    const first = await aesGcmSeal(key, utf8('bonjour'), aad);
    const second = await aesGcmSeal(key, utf8('bonjour'), aad);
    expect(first).toHaveLength(12 + 7 + 16);
    expect(first.slice(0, 12)).not.toEqual(second.slice(0, 12));
    expect(new TextDecoder().decode(await aesGcmOpen(key, first, aad))).toBe('bonjour');
    await expect(aesGcmOpen(key, first.slice(0, 27), aad)).rejects.toThrow(OpenError);
    await expect(aesGcmSeal(key, utf8('x'), new Uint8Array())).rejects.toThrow(/additional data/);
  });
});

describe('what the browser seals', () => {
  // The Runner opens this file (TestWhatTheBrowserSealedOpens). It is rewritten
  // on every run; the deterministic seeds keep it byte-identical.
  it('is written for the Runner to open', async () => {
    const recipient = await deterministicBytes(utf8('crewdeck-web/recipient'), 32);
    const { publicKey } = await x25519FromPrivateKey(recipient);
    const wrapSeed = utf8('crewdeck-web/wrap');
    const wrapAad = utf8('dev_01J9ZQ3M:1');
    const vaultKey = utf8('a 32-byte vault key from the web');
    const wrap = await withDeterministicRandom(wrapSeed, () => hpkeSeal(publicKey, vaultKey, INFO.vaultWrap, wrapAad));

    const aesSeed = utf8('crewdeck-web/aes-gcm');
    const aesKey = utf8('a 32-byte item key from the web.');
    const aesAad = utf8('ses_01J9ZQ5X:input:in_01J9ZQ6A');
    const message = utf8('{"type":"message","text":"Lance les tests"}');
    const sealed = await withDeterministicRandom(aesSeed, async () => aesGcmSeal(await importAesKey(aesKey), message, aesAad));

    const file = {
      description: 'Written by the browser (apps/web/src/keys/crypto.spec.ts, Chromium WebCrypto), opened by the Runner.',
      wrap: {
        name: 'web-vault-wrap',
        seed: toBase64Url(wrapSeed),
        recipientPrivateKey: toBase64Url(recipient),
        recipientPublicKey: toBase64Url(publicKey),
        info: INFO.vaultWrap,
        aad: toBase64Url(wrapAad),
        plaintext: toBase64Url(vaultKey),
        enc: toBase64Url(wrap.enc),
        ciphertext: toBase64Url(wrap.ciphertext),
      },
      aesGcm: {
        name: 'web-session-input',
        seed: toBase64Url(aesSeed),
        key: toBase64Url(aesKey),
        aad: toBase64Url(aesAad),
        plaintext: toBase64Url(message),
        sealed: toBase64Url(sealed),
      },
    };
    await server.commands.writeFile(fixtures + 'web-seal.json', JSON.stringify(file, null, 2) + '\n');
    expect(await readVectors<typeof file>('web-seal.json')).toEqual(file);
  });
});
